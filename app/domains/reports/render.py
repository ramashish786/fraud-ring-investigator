"""Deterministic Markdown rendering of a structured report (no LLM involved)."""

from __future__ import annotations

from typing import Any

LEVEL_LABEL = {
    "verified_fact": "Verified fact",
    "observed_relationship": "Observed relationship",
    "inferred_pattern": "Inferred pattern",
    "hypothesis": "Hypothesis",
    "confirmed_outcome": "Confirmed outcome",
}


def _claims(title: str, claims: list[dict[str, Any]]) -> list[str]:
    if not claims:
        return [f"### {title}", "_None identified._", ""]
    lines = [f"### {title}"]
    for c in claims:
        refs = ", ".join(c.get("evidence_refs", [])) or "**unsupported, no evidence**"
        lines.append(f"- {c['statement']} [{refs}]")
    return [*lines, ""]


def render_markdown(r: dict[str, Any]) -> str:
    risk, review, n = r["risk_assessment"], r["human_review"], r["narrative"]
    out = [
        f"# Investigation report: {r['alert']['external_ref']}",
        "",
        f"Alert type: {r['alert']['alert_type']} · Subject account: {r['alert']['subject_account_id']} · "
        f"Report version {r['version']}",
        "",
        "## Summary",
        n["investigation_summary"],
        "",
        "## Risk assessment (deterministic rules)",
        f"**Score {risk['score']}/100 ({risk['category']})**, ruleset {risk['ruleset_version']}.",
        f"_{risk['disclaimer']}_",
        "",
        "| Rule | Description | Weight | Evidence |",
        "|---|---|---|---|",
    ]
    out += [
        f"| {f['rule_id']} | {f['description']} | {f['weight']:+g} | {', '.join(f['evidence_refs'][:4])} |"
        for f in risk["factors"]
    ] or ["| none | no rule fired | 0 | |"]
    out += [
        "",
        "## Human review",
        f"Decision: **{review['decision']}**" + (f": {review['comment']}" if review.get("comment") else ""),
        "",
        "## Suspicious entities (hypotheses)",
    ]
    out += [
        f"- {e['account_id']}: {e['role_hypothesis']} [{', '.join(e['evidence_refs'])}]"
        for e in n["suspicious_entities"]
    ] or ["_None._"]
    out += [""]
    out += _claims("Transaction patterns", n["transaction_patterns"])
    out += _claims("Graph relationships", n["graph_relationships"])
    out += _claims("Historical case similarities", n["historical_case_similarities"])
    out += _claims("Supporting evidence", n["supporting_evidence"])
    out += _claims("Contradictions and legitimate explanations", n["contradictions"])
    out += ["### Missing information"] + ([f"- {m}" for m in n["missing_information"]] or ["_None._"]) + [""]
    out += ["## Recommended next steps"] + [f"- {s}" for s in n["recommended_next_steps"]] + [""]
    out += ["## Evidence appendix", "| Ref | Level | Kind | Summary |", "|---|---|---|---|"]
    out += [
        f"| {e['ref']} | {LEVEL_LABEL.get(e['level'], e['level'])} | {e['kind']} | {e['summary'].replace('|', '/')} |"
        for e in r["evidence"]
    ]
    meta = r["generation"]
    out += [
        "",
        f"_Narrative generated by {meta['model']}; {meta['unsupported_claims']} unsupported claim(s); "
        f"{meta['validation_problems']} validation problem(s) after retry._",
    ]
    return "\n".join(out)
